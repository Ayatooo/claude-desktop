// Builds the ASCII scenes once and writes them to hooks/generated-scenes.ts,
// which the mod loads as is (nothing is computed at startup).
//
//   node --experimental-strip-types tools/build-scenes.mjs [scene...]
//
// With no argument, every scene. Run it again after changing a scene, its
// models, ascii.ts or stage.ts.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

// Scene id → [module, exported constant].
const SCENES = {
  ocean: ['ocean.ts', 'OCEAN_SVG'],
  'ocean-thumb': ['ocean-thumb.ts', 'OCEAN_THUMB'],
  koi: ['koi.ts', 'KOI_SVG'],
  'koi-thumb': ['koi-thumb.ts', 'KOI_THUMB'],
  autumn: ['autumn.ts', 'AUTUMN_SVG'],
  'autumn-thumb': ['autumn-thumb.ts', 'AUTUMN_THUMB'],
  bloom: ['bloom.ts', 'BLOOM_SVG'],
  'bloom-thumb': ['bloom.ts', 'BLOOM_THUMB'],
}
// The most characters a backdrop's SVG may hold.
const LIMIT = 131072

const hooks = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'hooks')
const out = path.join(hooks, 'generated-scenes.ts')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'scenes-'))
for (const f of fs.readdirSync(hooks).filter(f => f.endsWith('.ts') && !f.endsWith('.d.ts'))) {
  // Node needs the extension in import paths: add it in a copy.
  const src = fs.readFileSync(path.join(hooks, f), 'utf8').replace(/from '\.\/([\w-]+)'/g, "from './$1.ts'")
  fs.writeFileSync(path.join(tmp, f), src)
}

// Start from the scenes already built, so one scene can be rebuilt alone.
const previous = {}
if (fs.existsSync(out)) {
  for (const m of fs.readFileSync(out, 'utf8').matchAll(/^export const (\w+) = (".*")$/gm)) previous[m[1]] = JSON.parse(m[2])
}
const wanted = process.argv.slice(2).length ? process.argv.slice(2) : Object.keys(SCENES)
let failed = false
for (const name of wanted) {
  const [file, constant] = SCENES[name] ?? []
  if (!file || !fs.existsSync(path.join(hooks, file))) {
    console.log(`${name}: no module, skipped.`)
    continue
  }
  const t0 = Date.now()
  const svg = (await import(path.join(tmp, file)))[constant]
  // The app loads a backdrop as an XML document: a bare & or a < in a text
  // breaks the whole drawing.
  const bad = svg.match(/&(?!(amp|lt|gt|quot|apos|#\d+|#x[0-9a-f]+);)/i)
  if (bad) {
    console.error(`${name}: an unescaped & at ${bad.index}: …${svg.slice(Math.max(0, bad.index - 40), bad.index + 10)}…`)
    failed = true
    continue
  }
  if (svg.length > LIMIT) {
    console.error(`${name}: too large, ${svg.length} characters (limit ${LIMIT}).`)
    failed = true
    continue
  }
  previous[constant] = svg
  console.log(`${name}: ${svg.length} characters, ${Date.now() - t0} ms.`)
}
fs.rmSync(tmp, { recursive: true, force: true })
const body = Object.entries(previous)
  .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)}`)
  .join('\n')
fs.writeFileSync(out, `// Generated by tools/build-scenes.mjs: do not edit by hand.\n${body}\n`)
if (failed) process.exit(1)
